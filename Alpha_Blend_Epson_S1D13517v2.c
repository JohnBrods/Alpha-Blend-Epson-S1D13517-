void Write_Number(uint32_t value, uint16_t x, uint16_t y, uint8_t colour)
{
    uint8_t buffer[12];
    int index = 0;

    do {
        buffer[index++] = '0' + (value % 10);
        value /= 10;
    } while (value > 0);

    while (index > 0) {
        index--;
        switchCharacter(buffer[index], x, y, colour);
        x += Letter_Font_Width;
    }
}

