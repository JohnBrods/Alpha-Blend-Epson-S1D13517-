void Write_Picture(uint32_t Actual_Sector, uint8_t sdram_Location_Number){

    uint16_t i=0;
    uint32_t Byte10;
    uint32_t Byte11;
    uint32_t Byte12;
    uint32_t Byte13;
    uint32_t image_data_Starts_at;

    uint16_t Byte18;
    uint16_t Byte19;
    uint16_t image_Width;

    uint32_t Byte22;
    uint32_t Byte23;
    uint32_t Byte24;
    uint32_t Byte25;
    uint32_t image_Height;

    uint32_t Image_Total_Bytes;
    uint32_t bytes_left_to_Read;

    uint16_t max_Bytes = 512;
    uint16_t Set_Start_Column, Set_Start_Row;
    uint16_t Set_End_Column, Set_End_Row;
    uint16_t sectors_to_Read = 0;

    signed   int signed_height;
    uint32_t x = 0;

    Read_Sector(Actual_Sector * Bytes_Per_Sector, dataBuffer);  //ACTUAL SECTOR WHERE PICTURE STARTS, NOT THE SAME AS START OF FILE. THIS IS READING THE BITMAP HEADER

    if(dataBuffer[0] != 66 && dataBuffer[1] != 77){
       Clear_Screen_S1D13517(red);
       write_text("NOT A BITMAP", 130,30, white);  }

    Byte10 = dataBuffer[10];
    Byte11 = dataBuffer[11]<<8;
    Byte12 = dataBuffer[12]<<16;
    Byte13 = dataBuffer[13]<<24;

    image_data_Starts_at = Byte10 + Byte11 + Byte12 + Byte13;  //Image starts at (from bmp header) 13,12,11,10

    Byte18 = dataBuffer[18];
    Byte19 = dataBuffer[19]<<8;

    image_Width = Byte18 + Byte19; //Image Width

    Byte22 =  dataBuffer[22];
    Byte23 =  dataBuffer[23]<<8;
    Byte24 =  dataBuffer[24]<<16;
    Byte25 =  dataBuffer[25]<<24;

    signed_height = Byte22 + Byte23 + Byte24 + Byte25;
    image_Height = abs(signed_height);

    sectors_to_Read = File.totalFileSize / Bytes_Per_Sector;  //Total File size divided by 512 = ? sectors
    bytes_left_to_Read = File.totalFileSize %512;             //Total File size divided by 512 = ?sectors and balance / remainder = header, usually 72 bytes

    Image_Total_Bytes = image_Width * image_Height + bytes_left_to_Read;

    if(bytes_left_to_Read >0){
       sectors_to_Read +=1;     //sectors_to_Read = sectors_to_Read+1;
    }

    Epson_CS = 0;
    write_command_EpsonS1D13517(0x52);    //page 73 Input Mode Register
    write_data_EpsonS1D13517(sdram_Location_Number<<4 | 0b0000);  //WORKS FOR Single buffers not PIP  bit 3 is Transparency

    Set_Start_Column = 0;
    Set_Start_Row    = 0;

    Set_End_Column   =  Set_Start_Column-2 + (image_Width/ 4);
    Set_End_Row      =  Set_Start_Row + (image_Height / 4);

    Epson_CS = 0;  //PAGE 75
    write_command_EpsonS1D13517(0x5A);
    write_data_EpsonS1D13517(Set_Start_Column);
    write_data_EpsonS1D13517(Set_Start_Row);
    write_data_EpsonS1D13517(0);
    write_data_EpsonS1D13517(Set_End_Column);
    write_data_EpsonS1D13517(Set_End_Row);
    write_data_EpsonS1D13517(3);

    for(i=0; i<sectors_to_Read; i++){

    Read_Sector(Bytes_Per_Sector * Actual_Sector, dataBuffer);

    if(i==sectors_to_Read-1){
       max_Bytes = bytes_left_to_Read-2;
      }

    for(x = image_data_Starts_at; x<max_Bytes; x +=2){
       PMDIN = dataBuffer[x] | dataBuffer[x+1]<<8; }
       Actual_Sector++;
       image_data_Starts_at = 0;
    }

    Epson_CS = 1;
}

